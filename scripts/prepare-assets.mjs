import {readdir,readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const types={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.mjs':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.json':'application/json; charset=utf-8','.svg':'image/svg+xml','.csv':'text/csv; charset=utf-8','.txt':'text/plain; charset=utf-8'};
async function walk(dir,relative=''){
 const result=[];
 for(const entry of (await readdir(dir,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
  if(entry.name.startsWith('.'))throw Error('Hidden files must not be served.');
  const name=relative+entry.name,file=path.join(dir,entry.name);
  if(entry.isDirectory())result.push(...await walk(file,name+'/'));
  else if(entry.isFile()){
   const bytes=await readFile(file),type=types[path.extname(name)];
   if(!type)throw Error('Unsupported asset type: '+name);
   if(bytes.length>5_000_000)throw Error('Unexpectedly large asset: '+name);
   result.push({path:'/'+name,size:bytes.length,type,sha256:createHash('sha256').update(bytes).digest('hex'),etag:createHash('md5').update(bytes).digest('hex')});
  }else throw Error('Assets must be regular files.');
 }
 return result;
}
const entries=await walk(path.join(root,'public'));
const release=createHash('sha256').update(JSON.stringify(entries)).digest('hex').slice(0,24);
const manifest={release,files:Object.fromEntries(entries.map(x=>[x.path,{...x,key:'releases/'+release+x.path}]))};
await mkdir(path.join(root,'worker'),{recursive:true});
await writeFile(path.join(root,'worker/assets-manifest.mjs'),'// Generated by scripts/prepare-assets.mjs. Assets contain no server-data files.\nexport default '+JSON.stringify(manifest,null,2)+';\n');
console.log('Prepared '+entries.length+' private assets for release '+release+'.');
